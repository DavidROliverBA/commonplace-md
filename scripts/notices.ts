// Writes THIRD_PARTY_NOTICES.md: every package Commonplace ships or runs (package.json's
// dependencies and theirs, not the dev tools), with its licence and the licence's own text, as
// MIT, BSD, Apache and the others ask of copies people are given. `bun run notices` after adding
// or updating a dependency; test/notices.test.ts fails when the file is out of date.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";

const ROOT = join(import.meta.dir, "..");
export const NOTICES = join(ROOT, "THIRD_PARTY_NOTICES.md");

export interface Pkg {
  name: string;
  version: string;
  licence: string;
  home: string | null;
  /** The package's own licence file, or null when it ships none. */
  text: string | null;
}

/** Where `name` resolves from `from`, walking up node_modules folders as Node does. */
function locate(name: string, from: string): string | null {
  for (let d = from; ; d = dirname(d)) {
    const p = join(d, "node_modules", name, "package.json");
    if (existsSync(p)) return dirname(p);
    if (d === ROOT || d === dirname(d)) return null;
  }
}

const licenceOf = (j: any): string =>
  typeof j.license === "string" ? j.license : j.license?.type ?? (Array.isArray(j.licenses) ? j.licenses.map((l: any) => l.type ?? l).join(" OR ") : "UNKNOWN");
const homeOf = (j: any): string | null => {
  const r = typeof j.repository === "string" ? j.repository : j.repository?.url;
  const url = j.homepage ?? r ?? null;
  return url ? String(url).replace(/^git\+/, "").replace(/\.git$/, "").replace(/^git:\/\//, "https://").replace(/^github:/, "https://github.com/") : null;
};
function licenceText(dir: string): string | null {
  const f = readdirSync(dir).find((n) => /^(licen[cs]e|copying)(\.(md|txt|markdown))?$/i.test(n)) ?? readdirSync(dir).find((n) => /^(licen[cs]e|copying)/i.test(n));
  return f ? readFileSync(join(dir, f), "utf8").trim() : null;
}

/** Every production package, each name and version once, sorted by name. */
export function packages(): Pkg[] {
  const seen = new Map<string, Pkg>();
  const visit = (name: string, from: string, optional: boolean) => {
    const dir = locate(name, from);
    if (!dir) {
      if (optional) return;
      throw new Error(`${name} isn't installed (needed from ${from}); run bun install`);
    }
    const j = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    const key = `${j.name}@${j.version}`;
    if (seen.has(key)) return;
    const text = licenceText(dir);
    // A package.json without a licence field: name it from the licence file when that's clear.
    const licence = licenceOf(j) === "UNKNOWN" && text && /^(the )?mit licen[cs]e/i.test(text) ? "MIT" : licenceOf(j);
    seen.set(key, { name: j.name, version: j.version, licence, home: homeOf(j), text });
    for (const d of Object.keys(j.dependencies ?? {})) visit(d, dir, false);
    for (const d of Object.keys(j.optionalDependencies ?? {})) visit(d, dir, true);
    for (const d of Object.keys(j.peerDependencies ?? {})) if (!j.peerDependenciesMeta?.[d]?.optional) visit(d, dir, true);
  };
  const root = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
  for (const d of Object.keys(root.dependencies ?? {})) visit(d, ROOT, false);
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true }));
}

export function render(list: Pkg[]): string {
  const count = new Map<string, number>();
  for (const p of list) count.set(p.licence, (count.get(p.licence) ?? 0) + 1);
  const summary = [...count].sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(", ");
  const anchor = (p: Pkg) => `${p.name}-${p.version}`.replace(/[^a-z0-9]+/gi, "-").toLowerCase();
  return `# Third-party notices

<!-- Generated by \`bun run notices\` (scripts/notices.ts). Don't edit by hand. -->

Commonplace is MIT-licensed ([LICENSE](LICENSE)). It's built on the open-source packages below,
which it includes in the app, the standalone file and the server, or runs alongside them. Each stays
its authors' work, under its own licence, whose text follows.

${list.length} packages: ${summary}.

## Run alongside, not included

- **PostgreSQL** (PostgreSQL Licence) and **pgvector** (PostgreSQL Licence): the database, from the
  \`pgvector/pgvector\` image in \`docker-compose.yml\` and \`laptop/\`, or a hosted Postgres.
- **Bun** (MIT): the runtime, from the \`oven/bun\` image in the \`Dockerfile\`.
- **libheif** (LGPL-3.0), inside \`libheif-js\` below: used only on the server, in a separate
  process, to turn iPhone HEIC photos into JPEG (\`src/images.ts\`). It's the unmodified npm package;
  you can replace it with your own build of the same version. Its source is at
  <https://github.com/strukturag/libheif>.

## Packages

| Package | Version | Licence |
|---|---|---|
${list.map((p) => `| [${p.name}](#${anchor(p)}) | ${p.version} | ${p.licence} |`).join("\n")}

## Licence texts

${list
  .map(
    (p) => `### ${p.name} ${p.version}

<a id="${anchor(p)}"></a>
${p.licence}${p.home ? `, ${p.home}` : ""}

${p.text ? "```text\n" + p.text.replace(/```/g, "ʼʼʼ") + "\n```" : "_This package ships no licence file; its package.json states the licence above._"}
`,
  )
  .join("\n")}`;
}

if (import.meta.main) {
  const list = packages();
  writeFileSync(NOTICES, render(list));
  console.log(`THIRD_PARTY_NOTICES.md: ${list.length} packages`);
}
